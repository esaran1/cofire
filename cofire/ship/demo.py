"""Freeze the committable demo fixture. Offline, real numbers, under 200 MB.

A judge clones the repo on a laptop with no credentials and runs `make demo`.
That must serve every route with the numbers this project actually produced.

The full forecast index is 235 MB because it holds 38 issues at 912 cells with
27 targets each. The fixture keeps two issues, the latest and one from mid
2026, which is what the routes need: the Place Card and map read one issue at a
time, and the replay link reads the other.
"""

from __future__ import annotations

import json
import logging
import shutil
from pathlib import Path
from typing import Any

LOGGER = logging.getLogger("cofire.ship.demo")

DEMO = Path("demo")
ART = Path("artifacts")
MID_2026 = "2026-05-05"
SIZE_CAP_MB = 200


def _copy(src: Path, dst: Path) -> int:
    if not src.exists():
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dst, dirs_exist_ok=True)
        return sum(f.stat().st_size for f in dst.rglob("*") if f.is_file())
    shutil.copy2(src, dst)
    return dst.stat().st_size


def pick_issues(index: dict[str, Any]) -> list[str]:
    """The latest issue, and one from mid 2026 for the replay link."""
    issues = sorted(index.get("issues", []))
    if not issues:
        return []
    latest = issues[-1]
    mid = MID_2026 if MID_2026 in issues else issues[len(issues) // 2]
    return sorted({latest, mid})


def subset_index(index: dict[str, Any], issues: list[str]) -> dict[str, Any]:
    keep = set(issues)
    out = dict(index)
    out["cells"] = [c for c in index.get("cells", []) if c.get("issue") in keep]
    out["issues"] = issues
    out["demo_fixture"] = True
    out["demo_note"] = (
        f"Committed fixture: {len(issues)} of {len(index.get('issues', []))} "
        "issues, every cell of each. Numbers are the real ones."
    )
    return out


def build() -> Path:
    DEMO.mkdir(parents=True, exist_ok=True)
    index_path = ART / "forecast_index.json"
    if not index_path.exists():
        raise SystemExit("run `python -m cofire.ship.index_build` first")
    index = json.loads(index_path.read_text())
    issues = pick_issues(index)
    subset = subset_index(index, issues)

    dst = DEMO / "artifacts"
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "forecast_index.json").write_text(json.dumps(subset))

    # The look-3 results, whole: they are small and the hindcast screen shows
    # every one of them.
    for name in (
        "look3/coverage.csv", "look3/criteria.csv", "look3/reliability.csv",
        "look3/reliability_diagram.csv", "look3/width_ratio.csv",
        "look3/provenance.json",
        "rerun_a/multiplicity.csv", "rerun_a/subx_verdict.csv",
        "rerun_a/classification.csv", "rerun_a/classification_control.csv",
        "rerun_a/pid_coverage.csv", "rerun_a/baselines.csv",
        "ship/rendering.csv", "FREEZE_COMMIT",
    ):
        _copy(ART / name, dst / name)

    _copy(Path("app/lib/facts.json"), DEMO / "facts.json")
    _copy(Path("docs/PREREGISTRATION_LOOK3.md"), DEMO / "PREREGISTRATION_LOOK3.md")

    manifest = {
        "issues": issues,
        "n_cells": len(subset["cells"]),
        "domains": subset.get("domains", []),
        "targets": subset.get("targets", []),
        "look_index": 3,
        "freeze_commit": (ART / "FREEZE_COMMIT").read_text().strip()
        if (ART / "FREEZE_COMMIT").exists() else "",
        "note": "Generated by cofire.ship.demo. Do not hand-edit.",
    }
    (DEMO / "MANIFEST_DEMO.json").write_text(json.dumps(manifest, indent=2))

    size_mb = sum(f.stat().st_size for f in DEMO.rglob("*") if f.is_file()) / 1e6
    LOGGER.info(
        "demo fixture: %d issues %s, %d cells, %.1f MB of %d MB cap",
        len(issues), issues, len(subset["cells"]), size_mb, SIZE_CAP_MB,
    )
    if size_mb > SIZE_CAP_MB:
        raise SystemExit(f"demo fixture is {size_mb:.1f} MB, over the {SIZE_CAP_MB} MB cap")
    return DEMO


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    print(build())
