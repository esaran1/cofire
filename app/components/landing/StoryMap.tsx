"use client";

import { type Lang, locale, useT } from "@/lib/i18n";
import { domainLabel } from "@/lib/domainNames";
import { ReactNode, useState } from "react";
import story from "@/lib/story.json";

/**
 * Where COFIRE forecasts, and what it forecasts there, as one picture.
 *
 * Every 4 km cell is coloured by how dry it is expected to be compared with the
 * same week in past years. The value is a week-of-year percentile, so 50 means
 * typical; the scale diverges around 50 because on this issue every cell sat
 * between about 32 and 59, and a 0-to-100 ramp drew both areas one flat colour.
 *
 * The horizon toggle carries the argument. From 2 to 8 weeks the colours fade
 * toward typical: the forecast regressing to the mean as it looks further
 * ahead, which is why the page later treats the long range differently.
 *
 * The framed rectangles are the forecast areas, drawn as exactly what the grid
 * covers. County lines are context only. Outlining the counties instead would
 * claim coverage the grid does not have.
 *
 * Data from app/lib/story.json, generated by cofire.ship.story. Nothing here is
 * typed by hand.
 */

const SLATE = [74, 85, 104];
const PAPER = [236, 234, 226];
const EMBER = [179, 58, 26];
/** Half-width of the colour scale around typical, in percentile points. */
const HALF = 25;

function mix(a: number[], b: number[], t: number): string {
  const c = a.map((v, i) => Math.round(v + (b[i] - v) * t));
  return `rgb(${c[0]},${c[1]},${c[2]})`;
}

function colour(v: number): string {
  const t = Math.max(-1, Math.min(1, (v - 50) / HALF));
  return t >= 0 ? mix(PAPER, EMBER, t) : mix(PAPER, SLATE, -t);
}

function fmtDate(iso: string, lang: Lang): string {
  const d = new Date(`${iso}T12:00:00`);
  return d.toLocaleDateString(locale(lang), { day: "numeric", month: "long", year: "numeric" });
}

/** Colorado, with the cropped region marked, so the reader knows where this is. */
function Locator() {
  const { t } = useT();
  const m = story.map;
  const [vx, vy, vw, vh] = m.view;
  return (
    <svg
      viewBox={`-4 -4 ${m.width + 8} ${m.height + 8}`}
      className="h-auto w-20 md:w-24"
      role="img"
      aria-label={t("land.mapAria")}
    >
      <path d={m.state} fill="#eaebe4" stroke="#8a8f88" strokeWidth={1.2} vectorEffect="non-scaling-stroke" />
      <rect
        x={vx}
        y={vy}
        width={vw}
        height={vh}
        fill="none"
        stroke="#245e50"
        strokeWidth={1.6}
        vectorEffect="non-scaling-stroke"
      />
    </svg>
  );
}

export function StoryMap({ title, line }: { title: ReactNode; line: ReactNode }) {
  const { lang, t } = useT();
  const [hi, setHi] = useState(0);
  const m = story.map;
  const h = String(story.horizons[hi]);
  const summary = m.by_horizon[h as keyof typeof m.by_horizon];
  const [vx, vy, vw, vh] = m.view;
  const label = vw * 0.05;
  // Each name sits above its area unless it would run into a name already
  // placed (Dillon and Upper South Platte are neighbours), then below it.
  const placed: { x0: number; x1: number; y0: number; y1: number }[] = [];
  const labelY = new Map<string, number>();
  // Shorter names first, so a long name is the one that moves.
  for (const a of [...m.areas].sort((p, q) => p.name.length - q.name.length)) {
    const width = a.name.length * label * 0.56;
    const boxAt = (baseline: number) => ({ x0: a.x, x1: a.x + width, y0: baseline - label, y1: baseline + label * 0.25 });
    const hits = (b: { x0: number; x1: number; y0: number; y1: number }) =>
      placed.some((q) => b.x0 < q.x1 && q.x0 < b.x1 && b.y0 < q.y1 && q.y0 < b.y1);
    let y = a.y - label * 0.45;
    if (hits(boxAt(y))) y = a.y + a.h + label * 1.05;
    placed.push(boxAt(y));
    labelY.set(a.name, y);
  }

  return (
    // Three grid items so the phone order is headline, map, controls: with the
    // controls above the map, tapping "8 weeks out" changed a map that was off
    // screen. On wide screens the text and controls share the left column.
    <div className="grid gap-10 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] lg:grid-rows-[auto_auto] lg:gap-x-20 lg:gap-y-0">
      <div className="reveal lg:col-start-1 lg:row-start-1 lg:self-end">
        <h2 className="display max-w-[16ch] text-4xl leading-[1.12] [text-wrap:balance] md:text-6xl">
          {title}
        </h2>
        <p className="text-ink-soft mt-5 max-w-[40ch] text-lg leading-relaxed md:text-xl">{line}</p>
      </div>

      <figure className="relative mx-auto w-full max-w-[34rem] lg:col-start-2 lg:row-span-2 lg:row-start-1 lg:self-center">
        <svg
          viewBox={`${vx} ${vy} ${vw} ${vh}`}
          className="h-auto max-h-[82dvh] w-full"
          role="img"
          aria-label={t("land.areasAria", { h })}
        >
          {m.outlines.map((o) => (
            <path
              key={o.name}
              d={o.d}
              fill="none"
              stroke="#d5d8cf"
              strokeWidth={0.8}
              vectorEffect="non-scaling-stroke"
            />
          ))}
          {m.cells.map((c, i) => (
            <rect
              key={i}
              x={c.x}
              y={c.y}
              width={m.cell[0] + 0.06}
              height={m.cell[1] + 0.06}
              fill={colour(c.v[hi])}
              style={{ transition: "fill 700ms cubic-bezier(0.16, 1, 0.3, 1)" }}
            >
              <title>{`${domainLabel(c.d)}: ${c.v[hi].toFixed(0)}, where 50 is typical`}</title>
            </rect>
          ))}
          {m.areas.map((a) => (
            <g key={a.name}>
              {a.outline ? (
                <rect
                  x={a.x}
                  y={a.y}
                  width={a.w}
                  height={a.h}
                  fill="none"
                  stroke="#161a19"
                  strokeWidth={1.4}
                  vectorEffect="non-scaling-stroke"
                />
              ) : null}
              <text
                x={a.x}
                y={labelY.get(a.name) ?? a.y - label * 0.45}
                className="fill-ink"
                style={{ fontSize: label, fontFamily: "var(--font-sans)" }}
              >
                {a.name}
              </text>
            </g>
          ))}
        </svg>
      </figure>

      <div className="lg:col-start-1 lg:row-start-2 lg:self-start">
        <div className="flex flex-wrap gap-2 lg:mt-12" role="radiogroup" aria-label={t("land.range")}>
          {story.horizons.map((hz, i) => (
            <button
              key={hz}
              role="radio"
              aria-checked={i === hi}
              onClick={() => setHi(i)}
              className={`rounded-full px-4 py-2 text-sm transition-colors active:scale-[0.98] ${
                i === hi ? "bg-ink text-paper" : "bg-paper-sunk text-ink-soft hover:text-ink"
              }`}
            >
              {t("land.weeksOut", { h: hz })}
            </button>
          ))}
        </div>

        <div className="mt-8 max-w-sm">
          <div
            className="h-2.5 w-full rounded-full"
            style={{
              background: `linear-gradient(90deg, ${colour(50 - HALF)}, ${colour(50)}, ${colour(50 + HALF)})`,
            }}
          />
          <div className="text-mute mt-1.5 flex justify-between text-xs">
            <span>{t("land.lessDry")}</span>
            <span>{t("legend.typical")}</span>
            <span>{t("legend.drier")}</span>
          </div>
        </div>

        <p className="text-ink-soft mt-8 max-w-[38ch] leading-relaxed">
          {t("land.issued", { date: fmtDate(story.issue, lang) })}{" "}
          <span className="num text-ink">{Math.round(summary.share_below_typical * 100)}%</span>{" "}
          {t("land.share", { h })}
        </p>

        <div className="mt-10 flex items-center gap-4">
          <Locator />
          <span className="text-mute max-w-[16ch] text-xs leading-snug">
            {t("land.region")}
          </span>
        </div>
      </div>

    </div>
  );
}
