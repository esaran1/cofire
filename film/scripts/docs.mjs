/**
 * Write the parts of the film's documents that come from its data, so they
 * cannot drift from what renders:
 *
 * - SCRIPT.md, between <!-- narration:begin --> and <!-- narration:end -->:
 *   every line with its start time, its words filled from data, its word
 *   count, and the fields behind its numbers;
 * - STORYBOARD.md: one row per shot (timecode, duration, visual, camera,
 *   on-screen text, narration, sound cues, data fields with their sources).
 *
 *   node scripts/docs.mjs          # write
 *   node scripts/docs.mjs --check  # fail if either file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { clickTimes, data, FILM, fill, narration, timeline, words } from "./lib.mjs";

const TL = timeline(), NAR = narration(), F = data().fields;
const check = process.argv.includes("--check");
const mmss = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
const keys = (tpl) => [...tpl.matchAll(/\{([a-z0-9_]+)\}/g)].map((m) => m[1]);
const LINKS_NOTE = { denver_water_sources: "outside fact: Denver Water, \"Where does your water come from?\" (SOURCES.md)", denver_water_watershed: "outside fact: Denver Water, \"Watershed Protection\" (SOURCES.md)" };

// --- SCRIPT.md narration table -------------------------------------------------
let total = 0;
const rows = NAR.lines.map((l) => {
  const text = fill(l.en, "en", F);
  total += words(text);
  const fs = keys(l.en).map((k) => `\`${k}\` (${F[k].source})`);
  if (l.source) fs.push(LINKS_NOTE[l.source]);
  return `| ${l.id} | ${mmss(l.start)} | ${text} | ${words(text)} | ${fs.join("; ")} |`;
});
const block = [
  "<!-- narration:begin (generated by scripts/docs.mjs from script/narration.json; do not edit here) -->",
  "",
  `Filled from today's data. ${total} words (limit about 330).`,
  "",
  "| # | Starts | Line | Words | Fields behind its numbers |",
  "|---|---|---|---|---|",
  ...rows,
  "",
  "<!-- narration:end -->",
].join("\n");
const scriptPath = join(FILM, "SCRIPT.md");
const script = readFileSync(scriptPath, "utf8");
const a = script.indexOf("<!-- narration:begin"), b = script.indexOf("<!-- narration:end -->");
if (a < 0 || b < 0) throw new Error("SCRIPT.md has no narration markers");
const newScript = script.slice(0, a) + block + script.slice(b + "<!-- narration:end -->".length);

// --- STORYBOARD.md ---------------------------------------------------------------
const clicks = clickTimes();
const cuesIn = (s) => {
  const out = [];
  for (const c of clicks.filter((c) => c.shot === s.id)) out.push(`${c.shot === "product.es" ? "toggle" : "click"} at ${mmss(c.t)}`);
  for (const c of TL.sfx.cues.filter((c) => c.t >= s.start && c.t < s.end)) out.push(`${c.why} at ${mmss(c.t)}`);
  if (s.id === TL.sfx.weekly_ticks.shot) out.push("soft tick at each issue");
  return out;
};
const linesIn = (s) => NAR.lines.filter((l, i) => {
  const end = NAR.lines[i + 1]?.start ?? TL.duration;
  return l.start < s.end && end > s.start;
}).map((l) => `(${l.id}) ${fill(l.en, "en", F)}`);
const fieldsOf = (s) => {
  const ks = new Set([...s.fields.filter((k) => !k.includes("_i")), ...keys(s.text)]);
  const out = [...ks].filter((k) => F[k]).map((k) => `\`${k}\` = ${F[k].en} (${F[k].source})`);
  if (s.fields.some((k) => k.includes("_i"))) out.push(s.fields.filter((k) => k.includes("_i")).map((k) => `\`${k.replace("_i", "_N")}\` per issue or pair (film.json)`).join(", "));
  return out;
};
const esc = (x) => String(x).replace(/\|/g, "\\|").replace(/\n/g, " ");
const shots = TL.shots.map((s) => {
  const text = s.text ? s.text.replace(/\{([a-z0-9_]+)\}/g, (m, k) => (F[k] ? F[k].en : m)) : "";
  return `| ${s.id} | ${mmss(s.start)} | ${(s.end - s.start).toFixed(1)} s | ${esc(s.visual)} | ${esc(s.camera)} | ${esc(text)} | ${esc(linesIn(s).join(" "))} | ${esc([s.sound, ...cuesIn(s)].filter(Boolean).join("; "))} | ${esc(fieldsOf(s).join("; "))} |`;
});
const long = TL.shots.filter((s) => s.end - s.start > 6 && s.id !== "product.tap").map((s) => s.id);
const board = `# COFIRE demo film: storyboard

Generated by \`scripts/docs.mjs\` from \`script/timeline.json\`,
\`script/narration.json\` and \`public/data/film.json\`. Do not edit by hand:
change those files and run \`npm run docs\`.

- **Length:** ${mmss(TL.duration)} (target 2:30 to 2:55; the render fails
  over 3:00).
- **Shots:** ${TL.shots.length}, all at most 6 s except the magic moment
  (\`product.tap\`, ${(TL.shots.find((s) => s.id === "product.tap").end - TL.shots.find((s) => s.id === "product.tap").start).toFixed(1)} s).${long.length ? ` **Over 6 s: ${long.join(", ")}.**` : ""}
- **Parts:** ${TL.parts.map((p) => `${p.id} ${p.title} ${mmss(p.start)} to ${mmss(p.end)}`).join("; ")}.
- **Values:** shown as of the last data refresh. They are filled at render
  time, and the render fails on any number that is not traced
  (\`src/trace.ts\`).
- **Captures:** named in the Visual column; files are in
  \`public/captures/\`, written by \`capture/capture.mjs\`.

| Shot | Starts | Length | Visual | Camera | On-screen text | Narration | Sound | Data fields behind every number |
|---|---|---|---|---|---|---|---|---|
${shots.join("\n")}

## Vertical cut (1080x1920, first ${TL.vertical_duration} s)

| Shot | Starts | Ends | From | Note |
|---|---|---|---|---|
${TL.vertical.map((v) => `| ${v.id} | ${mmss(v.start)} | ${mmss(v.end)} | ${(v.from ?? []).join(", ")} | ${v.note ?? "the same scene, framed for a tall screen"} |`).join("\n")}
`;
const boardPath = join(FILM, "STORYBOARD.md");

if (check) {
  const stale = [];
  if (newScript !== script) stale.push("SCRIPT.md");
  if (readFileSync(boardPath, "utf8") !== board) stale.push("STORYBOARD.md");
  if (stale.length) throw new Error(`${stale.join(" and ")} out of date: run node scripts/docs.mjs`);
  console.log("SCRIPT.md and STORYBOARD.md are current");
} else {
  writeFileSync(scriptPath, newScript);
  writeFileSync(boardPath, board);
  console.log(`SCRIPT.md (${total} words) and STORYBOARD.md (${TL.shots.length} shots) written`);
}
